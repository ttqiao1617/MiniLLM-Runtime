#!/usr/bin/env python3
"""Shared, dependency-light helpers for the Qwen2.5 MiniLLM-RT path."""

from __future__ import annotations

import json
import os
from pathlib import Path
from typing import Any

import torch
from transformers import AutoConfig, AutoModelForCausalLM, AutoTokenizer


MODEL_ID = "Qwen/Qwen2.5-0.5B-Instruct"
MODEL_REVISION = "7ae557604adf67be50417f59c2c2f167def9a775"
WORKSPACE = Path(os.environ.get("MINILLM_WORKSPACE", "/workspace/trtllm_workspace"))
DEFAULT_MODEL_DIR = WORKSPACE / "qwen2.5-0.5b-instruct"
DEFAULT_ARTIFACT_ROOT = WORKSPACE / "minillm-rt/qwen2.5-0.5b-instruct"


def torch_dtype(name: str) -> torch.dtype:
    mapping = {
        "float32": torch.float32,
        "float16": torch.float16,
    }
    try:
        return mapping[name]
    except KeyError as exc:
        raise ValueError(f"unsupported dtype: {name}") from exc


def load_tokenizer(model_dir: str | Path):
    return AutoTokenizer.from_pretrained(
        str(model_dir),
        revision=MODEL_REVISION,
        local_files_only=True,
        trust_remote_code=False,
    )


def load_model(model_dir: str | Path, dtype: str, device: str = "cpu"):
    model = AutoModelForCausalLM.from_pretrained(
        str(model_dir),
        revision=MODEL_REVISION,
        local_files_only=True,
        trust_remote_code=False,
        dtype=torch_dtype(dtype),
        low_cpu_mem_usage=True,
        # Eager attention is the most portable path through the legacy ONNX
        # exporter and provides a simple numerical correctness reference.
        attn_implementation="eager",
    )
    model.eval()
    return model.to(device)


def load_config(model_dir: str | Path):
    return AutoConfig.from_pretrained(
        str(model_dir),
        revision=MODEL_REVISION,
        local_files_only=True,
        trust_remote_code=False,
    )


def make_position_ids(attention_mask: torch.Tensor) -> torch.Tensor:
    """Create explicit, padding-safe position IDs from a 2-D attention mask."""
    position_ids = attention_mask.to(torch.int64).cumsum(dim=-1) - 1
    position_ids.masked_fill_(attention_mask == 0, 0)
    return position_ids


def build_chat(tokenizer, system: str, user: str) -> tuple[str, dict[str, torch.Tensor]]:
    messages = []
    if system:
        messages.append({"role": "system", "content": system})
    messages.append({"role": "user", "content": user})
    rendered = tokenizer.apply_chat_template(
        messages,
        tokenize=False,
        add_generation_prompt=True,
    )
    encoded = tokenizer(rendered, return_tensors="pt", add_special_tokens=False)
    encoded["position_ids"] = make_position_ids(encoded["attention_mask"])
    return rendered, encoded


def eos_token_ids(model_dir: str | Path) -> list[int]:
    generation_path = Path(model_dir) / "generation_config.json"
    data: dict[str, Any] = {}
    if generation_path.exists():
        data = json.loads(generation_path.read_text(encoding="utf-8"))
    value = data.get("eos_token_id", load_config(model_dir).eos_token_id)
    return [int(value)] if isinstance(value, int) else [int(x) for x in value]


def write_model_spec(
    output: str | Path,
    model_dir: str | Path,
    dtype: str,
    engine_max_sequence_length: int,
) -> Path:
    """Write the strict key=value manifest consumed by the C++ ModelSpec."""
    config = load_config(model_dir)
    tokenizer = load_tokenizer(model_dir)
    head_dim = int(config.hidden_size) // int(config.num_attention_heads)
    values = {
        "model_name": "qwen2.5-0.5b-instruct",
        "num_hidden_layers": int(config.num_hidden_layers),
        "num_attention_heads": int(config.num_attention_heads),
        "num_kv_heads": int(config.num_key_value_heads),
        "head_dim": head_dim,
        "vocab_size": int(config.vocab_size),
        "model_max_position_embeddings": int(config.max_position_embeddings),
        "engine_max_sequence_length": int(engine_max_sequence_length),
        "input_ids_dtype": "int64",
        "attention_mask_dtype": "int64",
        "position_ids_dtype": "int64",
        "logits_dtype": dtype,
        "kv_dtype": dtype,
        "requires_position_ids": "true",
        "eos_token_ids": ",".join(str(x) for x in eos_token_ids(model_dir)),
        "pad_token_id": int(tokenizer.pad_token_id),
        "past_prefix": "past_key_values.",
        "present_prefix": "present.",
        "kv_layout": "bhsd",
    }
    path = Path(output)
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "# Generated by python/qwen_common.py for MiniLLM-RT.",
        "# Tensor names are prefix + layer + .key/.value.",
    ]
    lines.extend(f"{key}={value}" for key, value in values.items())
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path
